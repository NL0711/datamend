// Proposals and the audit sample for one run (moved here from the old Data pipeline page; the endpoints are unchanged). Proposals are
// generated suggestions: they change nothing until a reviewer accepts one, and the original value is always kept.
import { useCallback, useEffect, useState } from 'react';
import { decideAudit, decideProposal, drawAudit, getNarrator, listAudit, listProposals, makeProposals } from './api';
import { useAdmin } from './Login';
import type { AuditEstimate, AuditItem, NarratorStatus, PipelineProposal } from './types';
import { GeneratedBadge, NOT_MEASURED, Notice, btn, btnQuiet, formatError } from './ui';

export function ProposalsPanel({ runId }: { runId: number }) {
  const { signedIn } = useAdmin();
  const [proposals, setProposals] = useState<PipelineProposal[]>([]);
  const [audit, setAudit] = useState<{ items: AuditItem[]; estimate: AuditEstimate } | null>(null);
  const [ai, setAi] = useState<NarratorStatus | null>(null);
  useEffect(() => { getNarrator().then(setAi).catch(() => setAi(null)); }, []);
  const [busy, setBusy] = useState('');
  const [msg, setMsg] = useState<{ tone: 'info' | 'error'; text: string } | null>(null);

  const load = useCallback(() => {
    listProposals(runId, 'all').then((r) => setProposals(r.proposals)).catch((e) => setMsg({ tone: 'error', text: formatError(e) }));
    listAudit(runId).then(setAudit).catch((e) => setMsg({ tone: 'error', text: formatError(e) }));
  }, [runId]);
  useEffect(load, [load]);

  const run = async (label: string, fn: () => Promise<unknown>, done?: string) => {
    setBusy(label); setMsg(null);
    try { await fn(); if (done) setMsg({ tone: 'info', text: done }); } catch (e) { setMsg({ tone: 'error', text: formatError(e) }); } finally { setBusy(''); load(); }
  };

  return (
    <div className="space-y-3">
      {msg && <Notice tone={msg.tone}>{msg.text}</Notice>}
      <div className="flex gap-2 flex-wrap">
        <button className={btn} disabled={!signedIn || !!busy} onClick={() => void run('proposals', () => makeProposals(runId), 'Proposals generated by the rule-based baseline.')}>Generate proposals</button>
        <button className={btn} disabled={!signedIn || !!busy || !ai?.connected} title={ai?.connected ? 'Ask the connected AI to propose a reviewer label for each flagged day (up to 20 per press)' : 'AI not connected: set GEMINI_API_KEY in the server .env'}
                onClick={() => void run('aiproposals', async () => { const r = await makeProposals(runId, 'ai'); if (r.stopped) throw new Error(`Stopped early: ${r.stopped}`); }, 'AI proposals generated (generated text, not decisions; nothing changes until you accept).')}>Propose with AI</button>
        <button className={btnQuiet} disabled={!signedIn || !!busy} onClick={() => void run('audit', () => drawAudit(runId, 30), 'A random sample of 30 unflagged days was drawn.')}>Draw audit sample (30)</button>
      </div>
      {proposals.length === 0 ? <p className="text-xs text-slate-500">No proposals for run {runId} yet.</p> : (
        <ul className="space-y-2">{proposals.map((p) => (
          <li key={p.id} className={`rounded px-3 py-2 text-xs ${NOT_MEASURED}`}>
            <div className="flex items-center gap-2 flex-wrap"><GeneratedBadge /><span className="font-mono">{p.station_id}</span>
              <span className="font-mono text-slate-500">{p.kind}{p.original_mm !== null ? ` · ${p.original_mm} mm` : ''}</span><span className="ml-auto font-mono">{p.status}</span></div>
            <p className="mt-1">{p.text}</p>
            {p.status === 'pending' && (
              <div className="mt-2 flex gap-2"><button className={btn} disabled={!signedIn || !!busy} onClick={() => void run('p' + p.id, () => decideProposal(p.id, true))}>Accept</button>
                <button className={btnQuiet} disabled={!signedIn || !!busy} onClick={() => void run('p' + p.id, () => decideProposal(p.id, false))}>Reject</button></div>)}
          </li>))}</ul>)}
      {audit && audit.items.length > 0 && (
        <div className="space-y-2">
          <div className="text-xs"><b>Audit sample.</b> {audit.estimate.decided} judged of {audit.estimate.drawn}
            {audit.estimate.missed_fault_rate !== null && <> · missed-fault rate <b className="font-mono">{(audit.estimate.missed_fault_rate * 100).toFixed(1)}%</b>
              {audit.estimate.interval_95 && <> (95% {(audit.estimate.interval_95[0] * 100).toFixed(1)} to {(audit.estimate.interval_95[1] * 100).toFixed(1)}%)</>}</>}
            <span className="block text-slate-500">{audit.estimate.note}</span></div>
          <ul className="grid md:grid-cols-2 gap-1">{audit.items.map((a) => (
            <li key={a.id} className="flex items-center gap-2 text-[11px] border border-[#E2E8F2] rounded px-2 py-1">
              <span className="font-mono truncate flex-1" title={a.station_id}>{a.station_id} · row {a.row_ref}</span>
              {a.decision ? <span className="font-bold">{a.decision}</span> : (['ok', 'missed_fault', 'unsure'] as const).map((d) => (
                <button key={d} className={btnQuiet} disabled={!signedIn || !!busy} onClick={() => void run('a' + a.id, () => decideAudit(a.id, d))}>{d === 'missed_fault' ? 'missed' : d}</button>))}
            </li>))}</ul>
        </div>)}
    </div>);
}
