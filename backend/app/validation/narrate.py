"""Explanations and the AI chat: evidence in, stored generated text out (spec sections 6 and 7).

Read-only on runs: this module writes only to the explanations table. With no narrator configured, "explain with the narrator" and
chat raise NarratorUnavailable (the API answers 503 "AI narrator not connected"); nothing is answered from canned text.
"""
from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional, Union

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from backend.app.config import settings
from backend.app.validation.evidence import evidence_v1
from backend.app.validation.explain import BaselineExplainer, Explainer, NarratorExplainer, NarratorUnavailable
from backend.app.validation.gemini import GeminiExplainer
from backend.app.validation.models import Explanation, ValidationCheckHit, ValidationResult, ValidationRun

MAX_QUESTION_CHARS = 2000
log = logging.getLogger(__name__)


def get_narrator() -> Optional[Union[NarratorExplainer, GeminiExplainer]]:
    """The configured LLM, or None. A narrator URL (from .env or the dashboard's Settings, runtime_settings.py; a private or loopback
    address is refused unless NARRATOR_ALLOW_PRIVATE is set) wins. Otherwise the interim Gemini layer is used when GEMINI_API_KEY is set."""
    from backend.app.runtime_settings import effective      # runtime overrides on top of the environment
    eff = effective()
    if eff.narrator_url.strip():
        return NarratorExplainer(eff.narrator_url.strip(), eff.narrator_token, settings.NARRATOR_TIMEOUT_SECONDS)
    if settings.GEMINI_API_KEY.strip():
        return GeminiExplainer(settings.GEMINI_API_KEY, settings.GEMINI_MODEL, settings.GEMINI_BASE_URL, settings.GEMINI_TIMEOUT_SECONDS,
                               settings.GEMINI_CALLS_PER_MINUTE, settings.GEMINI_DAILY_CALL_BUDGET)
    return None


def narrator_status(narrator: Optional[Union[NarratorExplainer, GeminiExplainer]]) -> Dict[str, Any]:
    """Never includes a key or token. ``provider`` is 'gemini' or 'mcp-narrator'."""
    if narrator is None:
        return {"connected": False, "message": "AI narrator not connected", "implemented": False, "provider": None,
                "note": "Set GEMINI_API_KEY in .env (interim) or NARRATOR_URL (the AI team's service); the rule-based baseline still works"}
    if isinstance(narrator, GeminiExplainer):
        return {"connected": True, "provider": "gemini", "model": narrator.model, "host": narrator.host, "implemented": True,
                "message": "Gemini is connected (interim, until the AI team's narrator is set; reachability is checked per request)"}
    return {"connected": True, "provider": "mcp-narrator", "host": narrator.host, "message": "narrator configured (reachability is checked per request)", "implemented": True}


def explanation_dict(e: Explanation) -> Dict[str, Any]:
    return {"id": e.id, "run_id": e.run_id, "result_id": e.result_id, "row_ref": e.row_ref, "check": e.check, "kind": e.kind,
            "question": e.question, "text": e.text, "contributions": e.contributions, "generator": e.generator, "model_id": e.model_id,
            "confidence": e.confidence, "confidence_note": "the narrator's own number" if e.confidence is not None else None,
            "generated": True, "label": "generated by fixed rules from the evidence" if e.generator == "baseline-rules" else "AI-generated",
            "created_at": e.created_at.isoformat() if e.created_at else None}


async def row_hits(session: AsyncSession, row: ValidationResult) -> List[ValidationCheckHit]:
    return list((await session.execute(select(ValidationCheckHit).where(ValidationCheckHit.result_id == row.id)
                                       .order_by(ValidationCheckHit.weight.desc(), ValidationCheckHit.id))).scalars())


async def _exported_provider(session: AsyncSession, row: ValidationResult) -> Optional[Dict[str, Any]]:
    """The provider block from the exported score file (SCORE_EXPORT_PATH) for the row's station and day; None when anything is missing."""
    from backend.app.pipeline.models import PipelineStation
    from backend.app.validation import score_provider
    try:
        prov = score_provider.get_provider(settings.SCORE_EXPORT_PATH)
    except score_provider.ScoreFileError as e:
        log.warning("score export file not used: %s", e)
        return None
    st = await session.get(PipelineStation, row.station_id)
    if prov is None or st is None:
        return None
    return prov.lookup(st.latitude, st.longitude, row.time_key)


async def evidence_for_row(session: AsyncSession, run: ValidationRun, row: ValidationResult, check: Optional[str] = None) -> List[Dict[str, Any]]:
    evs = [evidence_v1(run, row, h) for h in await row_hits(session, row) if check is None or h.check == check]
    if run.source == "pipeline" and evs:
        from backend.app.pipeline import scoring           # a stored model score for this row, or nothing: the block is never invented
        prov = await scoring.provider_block(session, run.id, row.row_ref)
        if prov is None and settings.SCORE_EXPORT_PATH.strip():
            prov = await _exported_provider(session, row)
        if prov is not None:
            for ev in evs:
                ev["provider"] = prov
    return evs


async def explain_row(session: AsyncSession, run: ValidationRun, row: ValidationResult, explainer: Explainer, check: Optional[str] = None) -> List[Explanation]:
    """Explain one fired check (or each fired check of the row) and store the reply. Raises NarratorUnavailable on any failure; stores nothing then."""
    evidences = await evidence_for_row(session, run, row, check)
    if not evidences:
        raise NarratorUnavailable("this row has no fired check to explain" if check is None else f"check {check!r} did not fire on this row")
    made: List[Explanation] = []
    for ev in evidences:
        ex = await explainer.explain(ev)
        made.append(Explanation(run_id=run.id, result_id=row.id, row_ref=row.row_ref, check=ev["check"], kind="explain", text=ex.text,
                                contributions=ex.contributions, generator=ex.generator, model_id=ex.model_id, confidence=ex.confidence, generated=True))
    session.add_all(made)
    await session.commit()
    return made


async def chat_turn(session: AsyncSession, run: ValidationRun, message: str, narrator: Optional[Union[NarratorExplainer, GeminiExplainer]],
                    row: Optional[ValidationResult] = None) -> Explanation:
    """One chat question to the narrator, grounded in the selected row's strongest evidence (or the run's headline numbers)."""
    message = (message or "").strip()
    if not message or len(message) > MAX_QUESTION_CHARS:
        raise ValueError(f"the question must be 1 to {MAX_QUESTION_CHARS} characters")   # the API validates first; this guards other callers
    if narrator is None:
        raise NarratorUnavailable("AI narrator not connected")
    evidence: Optional[Dict[str, Any]] = None
    context: Dict[str, Any] = {"run_headline": (run.report or {}).get("headline"), "run_not_run": run.not_run}
    if row is not None:
        evs = await evidence_for_row(session, run, row)
        if evs:
            evidence = evs[0]
            context["other_checks_on_row"] = [e["check"] for e in evs[1:]]
        context["row_verdict"] = row.verdict
    ex = await narrator.explain(evidence, question=message, kind="chat", context=context)
    saved = Explanation(run_id=run.id, result_id=row.id if row else None, row_ref=row.row_ref if row else None,
                        check=evidence["check"] if evidence else None, kind="chat", question=message, text=ex.text,
                        contributions=ex.contributions, generator=ex.generator, model_id=ex.model_id, confidence=ex.confidence, generated=True)
    session.add(saved)
    await session.commit()
    return saved


async def list_explanations(session: AsyncSession, run_id: int, row_ref: Optional[str] = None, kind: Optional[str] = None) -> List[Explanation]:
    q = select(Explanation).where(Explanation.run_id == run_id)
    if row_ref is not None:
        q = q.where(Explanation.row_ref == row_ref)
    if kind:
        q = q.where(Explanation.kind == kind)
    return list((await session.execute(q.order_by(Explanation.id))).scalars())


